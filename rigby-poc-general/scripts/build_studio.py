def build_page(
    store: TraceStore,
    library_root: Path,
    intake: list[dict] | None = None,
    run_tracks: dict[str, dict] | None = None,
) -> str:
    traces = [store.load(trace_id) for trace_id in store.list_ids()]
    library = PrimitiveLibrary(library_root)

    robots: dict[str, dict] = {}
    for trace in traces:
        robots.setdefault(trace["robot_id"], trace["robot"])

    libraries = {}
    for robot_id in robots:
        summary = library.load_summary(robot_id)
        records = library.load(robot_id)
        failures = library.load_failures(robot_id)
        certified: dict[str, list[str]] = {}
        for record in records:
            certified.setdefault(record.entry_id, []).append(record.remove)
        refused: dict[str, str] = {}
        for failure in failures:
            if failure.entry_id not in certified:
                refused[failure.entry_id] = failure.failed_gate or failure.failure_code
        libraries[robot_id] = {
            "afforded": list(summary.afforded_entry_ids) if summary else [],
            "certified_count": len(records),
            "attempted": summary.attempted if summary else None,
            "yield": round(summary.yield_fraction, 3) if summary else None,
            "coverage": round(summary.schema_coverage, 3) if summary else None,
            "elapsed_seconds": round(summary.elapsed_seconds, 1) if summary else None,
            "certified": {k: sorted(v) for k, v in sorted(certified.items())},
            "refused": dict(sorted(refused.items())),
        }

    audit_path = ROOT / "docs" / "audit-report.json"
    audit = (
        json.loads(audit_path.read_text(encoding="utf-8"))
        if audit_path.is_file()
        else None
    )

    inventory = load_inventory()
    schema_rows = [
        {
            "id": entry.entry_id,
            "gloss": entry.gloss,
            "kind": entry.schema.kind.value,
            "requires": sorted(item.value for item in entry.requires),
        }
        for entry in sorted(inventory.entries, key=lambda item: item.entry_id)
    ]

    payload = json.dumps(
        {
            "traces": traces,
            "robots": robots,
            "libraries": libraries,
            "audit": audit,
            "intake": intake or [],
            "inventory": schema_rows,
        },
        indent=None,
        sort_keys=True,
    )

    viewer = json.dumps(
        {"robots": _viewer_robots(), "runs": run_tracks or {}},
        separators=(",", ":"),
        sort_keys=True,
    )
    viewer_js = "\n".join(
        (Path(__file__).resolve().parent / name).read_text(encoding="utf-8")
        for name in ("studio_viewer.js", "studio_views.js")
    )

    return (
        _TEMPLATE.replace("__DATA__", payload)
        .replace("__VIEWER__", viewer)
        .replace("__VIEWER_JS__", viewer_js)
        .replace("__COUNT__", str(len(traces)))
    )


def _viewer_robots() -> dict[str, dict]:
    """Geometry and primitive tracks, from whatever export_viewer.py left behind.

    Missing is not fatal and must not be: the studio still builds without them,
    and every player says which command would produce the geometry it wants. A
    rebuild that silently dropped the 3D would be worse than one that explains
    itself.
    """

    directory = ROOT / "results" / "viewer"
    if not directory.is_dir():
        return {}
    out: dict[str, dict] = {}
    for path in sorted(directory.glob("*.json")):
        try:
            out[path.stem] = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as error:  # pragma: no cover
            print(f"{'':18} !! viewer payload {path.name}: {error}")
    return out


