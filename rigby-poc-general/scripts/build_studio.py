ROOT = Path(__file__).resolve().parents[1]
ZOO_ROOT = ROOT / "assets" / "general" / "zoo"
EXOTIC_ROOT = ROOT / "assets" / "general" / "exotic"

# The zoo is generated by this repository; the exotic set is fetched from an
# outside project and pinned. Keeping both in one studio is the point -- a claim
# about arbitrary robots is only worth as much as the robots nobody here wrote.
ROBOT_ROOTS = (ZOO_ROOT, EXOTIC_ROOT)


def discover() -> dict[str, Path]:
    """Every uploadable model across both roots, by id."""

    found: dict[str, Path] = {}
    for root in ROBOT_ROOTS:
        if not root.is_dir():
            continue
        for directory in sorted(root.iterdir()):
            source = directory / "robot.urdf"
            if source.is_file():
                found[directory.name] = source
    return found

SHARED_PROMPT = "reach out as far as you can and then come back"

PER_ROBOT_PROMPTS: dict[str, tuple[str, ...]] = {
    "zoo_tool_arm": ("sweep slowly across in front of you",),
    "zoo_jaw_arm": ("wave three times",),
    "zoo_hand_arm": ("trace a big circle",),
    "zoo_dual_arm": ("lower the tool down toward the table",),
    "zoo_compact_arm": ("reach out quickly, just a little",),
    "zoo_long_arm": ("sweep across the workspace, then hold still",),
    # The third-party arms get prompts of the same kind, not easier ones.
    "iiwa7": ("trace a big circle", "reach out slowly and hold there"),
    "kuka_lwr": ("sweep across in front of you", "wave twice"),
    "panda": ("reach out as far as you can, quickly", "trace a slow circle"),
}

# One of each refusal, so the studio shows what "no" looks like at every stage.
REFUSAL_PROMPTS: tuple[tuple[str, str], ...] = (
    ("zoo_jaw_arm", "drive across the room and open the door"),
    ("zoo_jaw_arm", "make me a sandwich"),
    ("zoo_jaw_arm", "hand it over to your other arm"),
    ("zoo_tool_arm", "pick it up and hold it"),
)


@dataclass(frozen=True, slots=True)
class Loaded:
    robot: object
    records: tuple
    failures: tuple
    centre: np.ndarray


def load(robot_id: str, library: PrimitiveLibrary, source: Path) -> Loaded:
    robot = ingest_robot(source, robot_id=robot_id)
    scale = robot.morphology.scale
    return Loaded(
        robot=robot,
        records=library.load(robot_id),
        failures=library.load_failures(robot_id),
        centre=np.array(
            [
                scale.workspace_centroid_m.x,
                scale.workspace_centroid_m.y,
                scale.workspace_centroid_m.z,
            ]
        ),
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--library", type=Path, default=ROOT / "robots")
    parser.add_argument("--out", type=Path, default=ROOT / "results")
    parser.add_argument("--no-render", action="store_true")
    arguments = parser.parse_args()

    inventory = load_inventory()
    library = PrimitiveLibrary(arguments.library)
    store = TraceStore(arguments.out)

    sources = discover()

    # Ingest everything first. A model that will not ingest cannot be prompted,
    # and *why* it was refused is a result worth recording rather than a reason
    # to quietly drop it from the run list.
    intake: list[dict[str, object]] = []
    run_tracks: dict[str, dict] = {}
    robot_ids: list[str] = []
    cache: dict[str, Loaded] = {}
    for robot_id, source in sources.items():
        origin = "zoo" if source.is_relative_to(ZOO_ROOT) else "third-party"
        try:
            loaded = load(robot_id, library, source)
        except Exception as error:  # noqa: BLE001 - the refusal is the record
            code = getattr(getattr(error, "code", None), "value", None)
            intake.append(
                {
                    "robot_id": robot_id,
                    "origin": origin,
                    "accepted": False,
                    "error": type(error).__name__,
                    "code": code,
                    "detail": str(error),
                }
            )
            print(f"{robot_id:<18} {'REFUSED@intake':<22} {code or type(error).__name__}")
            continue

        cache[robot_id] = loaded
        robot_ids.append(robot_id)
        morphology = loaded.robot.morphology
        intake.append(
            {
                "robot_id": robot_id,
                "origin": origin,
                "accepted": True,
                "morphology_class": morphology.morphology_class.value,
                "dofs": len(loaded.robot.manifest.dofs),
                "reach_m": round(morphology.scale.reach_radius_m, 3),
                "mass_kg": round(morphology.scale.total_mass_kg, 2),
                "effectors": [
                    {"kind": e.kind.value, "name": e.name} for e in morphology.effectors
                ],
                "notes": [note.detail for note in loaded.robot.integrity.notes],
            }
        )

    jobs: list[tuple[str, str]] = []
    for robot_id in robot_ids:
        jobs.append((robot_id, SHARED_PROMPT))
        for prompt in PER_ROBOT_PROMPTS.get(robot_id, ()):
            jobs.append((robot_id, prompt))
    jobs.extend(
        (robot_id, prompt)
        for robot_id, prompt in REFUSAL_PROMPTS
        if robot_id in cache
    )

    for robot_id, prompt in jobs:
        if robot_id not in cache:
            continue
        loaded = cache[robot_id]
        robot = loaded.robot

        result = answer(
            prompt,
            robot.manifest,
            robot.finalized.model,
            inventory,
            loaded.records,
            loaded.failures,
        )
        trace = result.trace

        clip_bytes = None
        if result.accepted and not arguments.no_render:
            frames = render_demo.render_trace(
                robot.finalized.model,
                result.certification.trace.qpos,
                result.certification.trace.times_s,
                centre=loaded.centre,
                reach=robot.morphology.scale.reach_radius_m,
            )
            scratch = arguments.out / "_scratch.gif"
            render_demo.write_gif(frames, scratch)
            clip_bytes = scratch.read_bytes()
            scratch.unlink(missing_ok=True)

        if result.accepted:
            # The simulated rollout, resampled for scrubbing. Same trace the
            # gates judged -- the viewer shows what the robot did, not the plan.
            run_tracks[trace.trace_id] = sample_track(
                result.certification.trace.times_s,
                result.certification.trace.qpos,
            )

        store.write(trace, clip_bytes=clip_bytes)
        verdict = "ok    " if result.accepted else f"refused@{result.failure_stage}"
        print(f"{robot_id:<18} {verdict:<22} {prompt[:52]}")

    # Contact probes. Every attempt is rendered, not only the ones that hold: a
    # failed grasp is the more informative clip, because you can watch the block
    # get knocked away or squeezed through the jaws instead of reading a gate
    # code and guessing.
    for robot_id in robot_ids:
        loaded = cache[robot_id]
        robot = loaded.robot

        outcome = probe_grasp(
            robot.manifest, robot.mjcf_xml, robot.finalized.model
        )
        clip_bytes = None
        if outcome.result is not None and not arguments.no_render:
            frames = render_demo.render_trace(
                outcome.scene.model,
                outcome.result.qpos,
                outcome.result.times_s,
                centre=np.asarray(outcome.scene.block_position_m),
                reach=robot.morphology.scale.reach_radius_m * 0.45,
            )
            scratch = arguments.out / "_scratch.gif"
            render_demo.write_gif(frames, scratch)
            clip_bytes = scratch.read_bytes()
            scratch.unlink(missing_ok=True)

        store.write(outcome.trace, clip_bytes=clip_bytes)
        verdict = (
            "held  "
            if outcome.trace.accepted
            else f"failed@{outcome.trace.failure['stage']}"
        )
        print(f"{robot_id:<18} {verdict:<22} grasp probe: pick up the block")

    (arguments.out / 'intake.json').write_text(
        json.dumps(intake, indent=2), encoding='utf-8'
    )
    page = build_page(store, arguments.library, intake, run_tracks)
    (arguments.out / "studio.html").write_text(page, encoding="utf-8")
    print(f"\n{len(store.list_ids())} traces -> {arguments.out / 'studio.html'}")
    return 0


