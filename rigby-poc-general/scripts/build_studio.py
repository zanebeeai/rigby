"""Run every demo prompt, record its trace, and emit a browsable studio page.

Refusals are run and recorded alongside the successes, deliberately. A gallery of
things that worked says nothing about what the system does when asked for
something it cannot do, and the five refusal stages -- firewall, planning,
binding, compilation, certification -- are the part of the design worth being
able to inspect.

The page inlines every trace but references the clips relatively, so it stays
around a megabyte and still opens by double-clicking, with no server.
"""

